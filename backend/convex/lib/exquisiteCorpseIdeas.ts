// The ideas Exquisite corpse offers under "Need an idea?", written by hand for each game language.
// Norwegian is not a translation of English. Every idea is a short noun phrase that works as the
// head, body or legs of a figure, must be drawable, and must make sense to a 16-year-old. A native
// speaker reads every list before it ships: no slurs, no crude second meanings, nothing that reads
// as a dig at someone's body. Ids are unique within a language and part, and never change once
// shipped, because finished figures store the id with the text.

export type IdeaLanguage = "en" | "nb";
export type IdeaPart = "head" | "body" | "legs";
export type Idea = { id: string; text: string };

const ideas = (part: IdeaPart, entries: readonly (readonly [string, string])[]): readonly Idea[] =>
  entries.map(([slug, text]) => ({ id: `${part}-${slug}`, text }));

